// =============================================================================
// test_MLPREG.cpp
// Unit tests for mc::MLPREG -- a multilayer perceptron as a function of its
// inputs and of its weights -- and for its external DAG operations
// mc::FFMLPREG, mc::FFGradMLPREG, mc::FFTanMLPREG and mc::FFAdjMLPREG:
// values against mc::MLP, Jacobian, directional derivatives and adjoints by
// passes through the layers against forward AD, symbolic differentiation in
// a DAG with the Jacobian or with the tangent and adjoint operations, bounds
// and relaxations, the home of an MLPREG in a DAG, networks read from ONNX
// files, and the gradient of a least-squares training loss.
//
// The ONNX models are generated by test_MLP_onnx.py. Each test prints PASS or
// FAIL and a summary is printed at the end; the process exits with code 0 if
// every test passes, 1 otherwise.
// =============================================================================

